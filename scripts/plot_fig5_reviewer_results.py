"""Plot the synthetic-prefill HyperTrace reviewer results for CHI Fig. 5.

The default input is generated by the three-stage synthetic reviewer check.
The output is therefore watermarked and must be regenerated from genuine
participant records before submission.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib as mpl
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


INK = "#1F2933"
MUTED = "#52606D"
GRID = "#CBD5E1"
RISK = "#6B7280"
STANDARD = "#3B78A8"
HYPERTRACE = "#D55E00"
WARNING = "#9B2C2C"

CONDITIONS = ("risk_only", "standard_signals", "hypertrace_evidence")
LABELS = ("Risk-only", "Standard\nsignals", "HyperTrace\nevidence")
COLORS = (RISK, STANDARD, HYPERTRACE)


def _participant_values(frame: pd.DataFrame, field: str) -> dict[str, np.ndarray]:
    values: dict[str, np.ndarray] = {}
    for condition in CONDITIONS:
        selected = frame.loc[frame["condition"] == condition]
        rates = selected.groupby("participant", sort=True)[field].mean().dropna()
        values[condition] = rates.to_numpy(dtype=float)
    return values


def _bootstrap_ci(values: np.ndarray, rng: np.random.Generator) -> tuple[float, float, float]:
    if values.size == 0:
        raise ValueError("Cannot bootstrap an empty participant set")
    indices = rng.integers(0, values.size, size=(10000, values.size))
    draws = values[indices].mean(axis=1)
    return (
        float(values.mean()),
        float(np.quantile(draws, 0.025)),
        float(np.quantile(draws, 0.975)),
    )


def _draw_participant_points(
    ax: plt.Axes,
    x: float,
    values: np.ndarray,
    color: str,
    rng: np.random.Generator,
    *,
    open_marker: bool = False,
    marker: str = "o",
) -> None:
    jitter = rng.uniform(-0.055, 0.055, size=values.size)
    face = "white" if open_marker else color
    ax.scatter(
        np.full(values.size, x) + jitter,
        100 * values,
        s=19,
        marker=marker,
        facecolors=face,
        edgecolors=color,
        linewidths=0.65,
        alpha=0.42,
        zorder=2,
    )


def _draw_estimate(
    ax: plt.Axes,
    x: float,
    estimate: tuple[float, float, float],
    color: str,
    *,
    open_marker: bool = False,
    marker: str = "o",
    label_value: bool = True,
) -> None:
    mean, lower, upper = (100 * value for value in estimate)
    ax.errorbar(
        [x],
        [mean],
        yerr=[[mean - lower], [upper - mean]],
        fmt=marker,
        markersize=6.5,
        markerfacecolor="white" if open_marker else color,
        markeredgecolor=color,
        markeredgewidth=1.25,
        color=color,
        elinewidth=1.45,
        capsize=3.2,
        capthick=1.2,
        zorder=4,
    )
    if label_value:
        ax.annotate(
            f"{mean:.1f}%",
            (x, upper),
            xytext=(0, 6),
            textcoords="offset points",
            ha="center",
            va="bottom",
            fontsize=8,
            color=INK,
            weight="bold",
        )


def _style_axis(ax: plt.Axes, title: str) -> None:
    ax.set_title(title, loc="left", fontsize=10, color=INK, weight="bold", pad=10)
    ax.set_ylim(-3, 108)
    ax.set_yticks([0, 25, 50, 75, 100])
    ax.set_yticklabels(["0", "25", "50", "75", "100"])
    ax.set_xticks(np.arange(3), LABELS)
    ax.tick_params(axis="x", length=0, pad=6)
    ax.tick_params(axis="y", length=3)
    ax.grid(axis="y", color=GRID, linewidth=0.65, alpha=0.62, zorder=0)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.spines["left"].set_color(GRID)
    ax.spines["bottom"].set_color(GRID)


def plot(frame: pd.DataFrame, output: Path) -> dict:
    required = {
        "participant",
        "condition",
        "initial_correct",
        "final_correct",
        "correct_ai_acceptance",
        "wrong_ai_rejection",
    }
    missing = sorted(required - set(frame.columns))
    if missing:
        raise ValueError(f"Input is missing required columns: {missing}")

    mpl.rcParams.update(
        {
            "font.family": "DejaVu Sans",
            "font.size": 8.5,
            "axes.labelsize": 9,
            "axes.edgecolor": GRID,
            "axes.labelcolor": INK,
            "xtick.color": MUTED,
            "ytick.color": MUTED,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "svg.fonttype": "none",
            "savefig.facecolor": "white",
            "savefig.edgecolor": "white",
        }
    )
    rng = np.random.default_rng(20260827)
    initial = _participant_values(frame, "initial_correct")
    final = _participant_values(frame, "final_correct")
    acceptance = _participant_values(frame, "correct_ai_acceptance")
    rejection = _participant_values(frame, "wrong_ai_rejection")

    summaries: dict[str, dict[str, dict[str, float]]] = {}
    for metric, values in (
        ("initial_accuracy", initial),
        ("final_accuracy", final),
        ("correct_ai_acceptance", acceptance),
        ("wrong_ai_rejection", rejection),
    ):
        summaries[metric] = {}
        for condition in CONDITIONS:
            mean, lower, upper = _bootstrap_ci(values[condition], rng)
            summaries[metric][condition] = {
                "estimate": mean,
                "ci_lower": lower,
                "ci_upper": upper,
                "participants": int(values[condition].size),
            }

    fig, axes = plt.subplots(1, 3, figsize=(7.2, 3.25), sharey=True)
    fig.subplots_adjust(left=0.075, right=0.992, bottom=0.235, top=0.835, wspace=0.24)
    fig.text(
        0.5,
        0.975,
        "SYNTHETIC PREFILL — REPLACE BEFORE SUBMISSION",
        ha="center",
        va="top",
        fontsize=8,
        color=WARNING,
        weight="bold",
    )

    ax = axes[0]
    _style_axis(ax, "(a) Initial and final accuracy")
    ax.set_ylabel("Estimated outcome (%)")
    for index, (condition, color) in enumerate(zip(CONDITIONS, COLORS)):
        initial_x = index - 0.13
        final_x = index + 0.13
        initial_values = initial[condition]
        final_values = final[condition]
        participant_order = sorted(
            frame.loc[frame["condition"] == condition, "participant"].unique()
        )
        initial_by_participant = (
            frame.loc[frame["condition"] == condition]
            .groupby("participant")["initial_correct"]
            .mean()
            .reindex(participant_order)
            .to_numpy()
        )
        final_by_participant = (
            frame.loc[frame["condition"] == condition]
            .groupby("participant")["final_correct"]
            .mean()
            .reindex(participant_order)
            .to_numpy()
        )
        for before, after in zip(initial_by_participant, final_by_participant):
            ax.plot(
                [initial_x, final_x],
                [100 * before, 100 * after],
                color=color,
                linewidth=0.65,
                alpha=0.20,
                zorder=1,
            )
        _draw_participant_points(ax, initial_x, initial_values, color, rng, open_marker=True, marker="D")
        _draw_participant_points(ax, final_x, final_values, color, rng)
        before = summaries["initial_accuracy"][condition]
        after = summaries["final_accuracy"][condition]
        _draw_estimate(
            ax,
            initial_x,
            (before["estimate"], before["ci_lower"], before["ci_upper"]),
            color,
            open_marker=True,
            marker="D",
            label_value=False,
        )
        _draw_estimate(
            ax,
            final_x,
            (after["estimate"], after["ci_lower"], after["ci_upper"]),
            color,
        )

    ax = axes[1]
    _style_axis(ax, "(b) Correct-AI acceptance")
    for index, (condition, color) in enumerate(zip(CONDITIONS, COLORS)):
        values = acceptance[condition]
        estimate = summaries["correct_ai_acceptance"][condition]
        _draw_participant_points(ax, index, values, color, rng)
        _draw_estimate(
            ax,
            index,
            (estimate["estimate"], estimate["ci_lower"], estimate["ci_upper"]),
            color,
        )

    ax = axes[2]
    _style_axis(ax, "(c) Wrong-AI rejection")
    for index, (condition, color) in enumerate(zip(CONDITIONS, COLORS)):
        values = rejection[condition]
        estimate = summaries["wrong_ai_rejection"][condition]
        _draw_participant_points(ax, index, values, color, rng)
        _draw_estimate(
            ax,
            index,
            (estimate["estimate"], estimate["ci_lower"], estimate["ci_upper"]),
            color,
        )

    legend_handles = [
        mpl.lines.Line2D(
            [], [], marker="D", linestyle="", markersize=5.5,
            markerfacecolor="white", markeredgecolor=INK, label="Initial judgment"
        ),
        mpl.lines.Line2D(
            [], [], marker="o", linestyle="", markersize=5.5,
            markerfacecolor=INK, markeredgecolor=INK, label="Final / assisted outcome"
        ),
        mpl.lines.Line2D(
            [], [], marker="o", linestyle="", markersize=3.8,
            color=MUTED, alpha=0.42, label="Participant-level proportion"
        ),
    ]
    fig.legend(
        handles=legend_handles,
        loc="lower center",
        bbox_to_anchor=(0.5, 0.035),
        ncol=3,
        frameon=False,
        fontsize=8,
        handletextpad=0.5,
        columnspacing=1.5,
    )

    output.parent.mkdir(parents=True, exist_ok=True)
    metadata = {
        "Title": "HyperTrace reviewer decisions and appropriate reliance",
        "Subject": (
            "Synthetic-prefill participant outcomes and participant-cluster bootstrap "
            "confidence intervals for three review-interface conditions."
        ),
        "Creator": "HyperTrace figure generator",
    }
    fig.savefig(output.with_suffix(".pdf"), bbox_inches="tight", pad_inches=0.06, metadata=metadata)
    fig.savefig(
        output.with_suffix(".svg"),
        bbox_inches="tight",
        pad_inches=0.06,
        metadata={"Title": metadata["Title"], "Creator": metadata["Creator"]},
    )
    fig.savefig(output.with_suffix(".png"), dpi=320, bbox_inches="tight", pad_inches=0.06)
    plt.close(fig)
    return summaries


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("review_ui/data/synthetic_experts_three_stage.csv"),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("docs/figures/generated/fig5_reviewer_results"),
    )
    args = parser.parse_args()
    frame = pd.read_csv(args.input)
    summaries = plot(frame, args.output)
    summary_path = args.output.with_name(f"{args.output.name}_summary.json")
    summary_path.write_text(json.dumps(summaries, indent=2), encoding="utf-8")
    print(json.dumps(summaries, indent=2))


if __name__ == "__main__":
    main()
